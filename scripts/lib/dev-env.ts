// The local `.env` for `pnpm dev:up` (#311): every setting the web, worker, migrate and seed processes read
// (config/env.ts), pointed at the compose services on 127.0.0.1, with a fresh secret for each one.

import { loadEnv } from '../../config/env.ts';

/** The port the dev web server listens on; `APP_URL` is built from it so sign-in links open the same server. */
export const WEB_PORT = 3100;

/** The text of a `.env` file for local development. `randomBytes(n)` returns n new random bytes on each call. */
export function devEnvText(randomBytes: (size: number) => Uint8Array): string {
  const secret = () => Buffer.from(randomBytes(24)).toString('hex'); // 48 hex characters: safe inside a URL
  const key = () => Buffer.from(randomBytes(32)).toString('base64'); // the 32-byte base64 key Next.js expects
  const owner = secret();
  const app = secret();
  const lines = [
    '# Generated by `pnpm dev:up` for local development: never commit it, never share it.',
    'LZP_ENV=development',
    `LZP_PG_SUPERUSER_PASSWORD=${secret()}`,
    `LZP_PG_OWNER_PASSWORD=${owner}`,
    `LZP_PG_APP_PASSWORD=${app}`,
    `DATABASE_URL=postgres://lzp_app:${app}@127.0.0.1:5432/letzeuspost`,
    `DATABASE_OWNER_URL=postgres://lzp_owner:${owner}@127.0.0.1:5432/letzeuspost`,
    'STORAGE_ENDPOINT=http://127.0.0.1:8333',
    'STORAGE_REGION=us-east-1',
    'STORAGE_BUCKET=letzeuspost-dev',
    'STORAGE_ACCESS_KEY_ID=lzp-dev',
    `STORAGE_SECRET_ACCESS_KEY=${secret()}`,
    'SMTP_URL=smtp://127.0.0.1:1025',
    'EMAIL_FROM=noreply@letzeuspost.invalid',
    `AUTH_SECRET=${key()}`,
    `APP_URL=http://localhost:${String(WEB_PORT)}`,
    `NEXT_SERVER_ACTIONS_ENCRYPTION_KEY=${key()}`,
    'NEXT_DEPLOYMENT_ID=dev',
  ];
  return `${lines.join('\n')}\n`;
}

/**
 * The arguments for the dev web server. It listens on this machine only: `next dev` otherwise listens on every
 * network interface, and the seeded app would be reachable from the local network.
 */
export function webDevArgs(): string[] {
  return [
    '--filter',
    '@lzp/web',
    'exec',
    'next',
    'dev',
    '--hostname',
    '127.0.0.1',
    '--port',
    String(WEB_PORT),
  ];
}

/** `KEY=value` lines to an object; comments and blank lines are skipped, and only the first `=` splits. */
export function parseEnvFile(text: string): Record<string, string> {
  const env: Record<string, string> = {};
  for (const raw of text.split(/\r\n?|\n/)) {
    const line = raw.trim();
    if (line === '' || line.startsWith('#')) continue;
    const at = line.indexOf('=');
    if (at > 0) env[line.slice(0, at).trim()] = line.slice(at + 1).trim();
  }
  return env;
}

/**
 * What is wrong with a `.env` the four local processes would read: one message per process that can't start, each
 * naming its missing or malformed settings and never a value (loadEnv's own messages). Empty when all is well.
 */
export function checkEnv(env: Readonly<Record<string, string | undefined>>): string[] {
  const problems: string[] = [];
  for (const name of ['web', 'worker', 'migrate', 'seed'] as const) {
    try {
      loadEnv(name, env);
    } catch (error) {
      problems.push(error instanceof Error ? error.message : String(error));
    }
  }
  return problems;
}
